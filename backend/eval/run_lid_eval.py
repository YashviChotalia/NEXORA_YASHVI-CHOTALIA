"""Language detection and routing on Indian-language speech (AI4Bharat Rasa, 22 languages).

For every clip it records three answers and compares them with the true language:
  whisper   Whisper's own language detection (restricted to ANVESH_ASR_LANGS, Urdu read as Hindi)
  indic     IndicConformer's identification among its 22 languages (speech/indic_asr.py `identify`)
  anvesh    what the app actually does (ASR._language, then IndicConformer for Indian languages other than Hindi)

  python eval/run_lid_eval.py --manifest eval/audio/multilingual/rasa/manifest.csv

Writes eval/results/multilingual/lid_results.md and lid_predictions.csv (no audio).
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
import time
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from anvesh.speech import audio as A  # noqa: E402
from anvesh.speech.indic_asr import LANGUAGES  # noqa: E402

NAME_TO_CODE = {v.lower(): k for k, v in LANGUAGES.items()}
OUT = Path(__file__).with_name("results") / "multilingual"
WHISPER_KNOWS = {"as", "bn", "gu", "hi", "kn", "ml", "mr", "ne", "pa", "sa", "sd", "ta", "te", "ur"}


def run(manifest: Path, cache: Path, budget: float) -> list[dict]:
    from anvesh.speech import models as M
    w = M.asr.get(block=True)
    ic = M.indic.get(block=True)
    if w is None or ic is None:
        raise SystemExit(f"models not available: asr={M.asr.status().error} indic={M.indic.status().error}")
    done = {}
    if cache.exists():
        for r in csv.DictReader(open(cache, encoding="utf-8")):
            done[r["path"]] = r
    rows = [r for r in csv.DictReader(open(manifest, encoding="utf-8"))]
    t0 = time.time()
    for r in rows:
        if r["path"] in done:
            continue
        true = NAME_TO_CODE.get(r["lang"].lower(), r["lang"])
        x = A.decode((manifest.parent / r["path"]).read_bytes())
        lang_w = M.asr._language(w, x)
        ranked = ic.identify(x)
        lang_i = ranked[0][0]
        app = lang_w
        if M.ASR.use_indic(lang_w):
            app = lang_i
        done[r["path"]] = {"path": r["path"], "true": true, "label": r["label"], "whisper": lang_w, "indic": lang_i,
                           "anvesh": app, "indic_top3": json.dumps([k for k, _ in ranked[:3]])}
        if len(done) % 50 == 0:
            _save(cache, done)
            print(f"  {len(done)}/{len(rows)} clips, {time.time() - t0:.0f}s", flush=True)
        if budget and time.time() - t0 > budget:
            break
    _save(cache, done)
    return [done[r["path"]] for r in rows if r["path"] in done]


def _save(cache: Path, done: dict) -> None:
    cache.parent.mkdir(parents=True, exist_ok=True)
    with open(cache, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["path", "true", "label", "whisper", "indic", "anvesh", "indic_top3"])
        w.writeheader()
        w.writerows(done.values())


def report(rows: list[dict]) -> str:
    by = defaultdict(list)
    for r in rows:
        by[r["true"]].append(r)
    acc = lambda rs, k: sum(r[k] == r["true"] for r in rs) / len(rs)  # noqa: E731
    top3 = lambda rs: sum(r["true"] in json.loads(r["indic_top3"]) for r in rs) / len(rs)  # noqa: E731
    L = ["# Language detection and routing: 22 Indian languages\n",
         "AI4Bharat Rasa, every clip on its own (a few seconds of speech). *Anvesh* = what the app does: Whisper "
         "detects; for Indian languages other than Hindi, IndicConformer decides which one. Hindi is the expected "
         "answer for Hindi clips (transcribed by Whisper). Generated by `eval/run_lid_eval.py`.\n",
         "| Language | Code | Clips | Whisper alone | IndicConformer alone | IndicConformer top 3 | **Anvesh routing** | "
         "Most common Anvesh mistake |", "|---|---|---|---|---|---|---|---|"]
    for code in sorted(by, key=lambda c: LANGUAGES.get(c, c)):
        rs = by[code]
        wrong = [r["anvesh"] for r in rs if r["anvesh"] != code]
        common = max(set(wrong), key=wrong.count) if wrong else "-"
        note = "" if code in WHISPER_KNOWS else " ¹"
        L.append(f"| {LANGUAGES.get(code, code)}{note} | {code} | {len(rs)} | {100 * acc(rs, 'whisper'):.0f}% | "
                 f"{100 * acc(rs, 'indic'):.0f}% | {100 * top3(rs):.0f}% | **{100 * acc(rs, 'anvesh'):.0f}%** | "
                 f"{LANGUAGES.get(common, common)} |")
    L.append(f"| **All** | | {len(rows)} | {100 * acc(rows, 'whisper'):.0f}% | {100 * acc(rows, 'indic'):.0f}% | "
             f"{100 * top3(rows):.0f}% | **{100 * acc(rows, 'anvesh'):.0f}%** | |")
    L.append("\n¹ Whisper has no model for this language, so it can only send the call onwards as 'some Indian "
             "language'; the officer can also set the language at intake, which skips detection entirely.\n")
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", required=True)
    ap.add_argument("--budget", type=float, default=0)
    ap.add_argument("--from-cache", action="store_true")
    a = ap.parse_args(argv)
    cache = OUT / "lid_predictions.csv"
    if a.from_cache:
        rows = list(csv.DictReader(open(cache, encoding="utf-8")))
    else:
        rows = run(Path(a.manifest), cache, a.budget)
    md = report(rows)
    (OUT / "lid_results.md").write_text(md, encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
